// Кириллические буквы, совпадающие по форме с латинскими
const ALIAS: Record<string, string> = {
	А: 'A',
	В: 'B',
	Е: 'E',
	Ё: 'E',
	К: 'K',
	М: 'M',
	Н: 'H',
	О: 'O',
	Р: 'P',
	С: 'C',
	Т: 'T',
	Х: 'X',
	а: 'a',
	е: 'e',
	о: 'o',
	р: 'p',
	с: 'c',
	у: 'y',
	х: 'x',
};

const glyphFor = (ch: string): string[] => {
	if (G[ch]) return G[ch];
	if (ALIAS[ch]) return G[ALIAS[ch]];
	const up = ch.toUpperCase();
	if (G[up]) return G[up];
	if (ALIAS[up]) return G[ALIAS[up]];
	return G['?'];
};

export type TextPixel = {
	// координаты левого нижнего угла пикселя; y растёт вверх, базовая линия y = 0
	x: number;
	y: number;
	glyph: number;
	// 0 = верх буквы, 1 = низ (для градиента)
	v: number;
};

export type TextLayout = {
	pixels: TextPixel[];
	width: number;
	// центр каждого символа по x
	glyphCenters: number[];
};

export const layoutText = (text: string): TextLayout => {
	const pixels: TextPixel[] = [];
	const glyphCenters: number[] = [];
	let cursor = 0;
	let glyph = 0;
	for (const ch of text) {
		const rows = glyphFor(ch);
		const w = rows[0].length;
		if (ch !== ' ') {
			for (let r = 0; r < rows.length; r++) {
				for (let c = 0; c < w; c++) {
					if (rows[r][c] === '#') {
						pixels.push({x: cursor + c, y: 6 - r, glyph, v: Math.min(1, r / 6)});
					}
				}
			}
		}
		glyphCenters.push(cursor + w / 2);
		cursor += w + 1;
		glyph++;
	}
	return {pixels, width: Math.max(0, cursor - 1), glyphCenters};
};

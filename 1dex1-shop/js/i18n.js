const KEY = 'dex.lang';
let lang = 'ru';
try {
	if (localStorage.getItem(KEY) === 'en') lang = 'en';
} catch {
	// приватный режим — язык по умолчанию
}

export const LANGS = ['ru', 'en'];
export const getLang = () => lang;
export const locale = () => (lang === 'en' ? 'en-GB' : 'ru-RU');

// Текст по ключу; {имя} в тексте заменяется значением из vars
export const t = (key, vars) => {
	let s = DICT[lang][key] ?? DICT.ru[key] ?? key;
	if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
	return s;
};

// Перевести размеченные элементы на странице
export const applyI18n = (root = document) => {
	for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
	for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
	for (const el of root.querySelectorAll('[data-i18n-attr]')) {
		for (const pair of el.dataset.i18nAttr.split(';')) {
			const [attr, key] = pair.split(':');
			el.setAttribute(attr, t(key));
		}
	}
	document.documentElement.lang = lang;
};

const listeners = new Set();
export const onLang = (fn) => listeners.add(fn);
export const setLang = (next) => {
	if (next === lang || !DICT[next]) return;
	lang = next;
	try {
		localStorage.setItem(KEY, next);
	} catch {
		// не запомнится — не страшно
	}
	applyI18n();
	listeners.forEach((fn) => fn(lang));
};

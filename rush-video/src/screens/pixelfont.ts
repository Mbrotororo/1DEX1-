type Glyph = {w: number; cells: [number, number][]};
const cache = new Map<string, Glyph>();

const glyph = (ch: string): Glyph => {
	let g = cache.get(ch);
	if (g) return g;
	const rows = LC[ch];
	if (rows) {
		const cells: [number, number][] = [];
		rows.forEach((row, r) => [...row].forEach((c, x) => c === '#' && cells.push([x, r])));
		g = {w: rows[0].length, cells};
	} else {
		// всё остальное — из шрифта ядра (y там растёт вверх от базовой линии: строка = 6 - y)
		const lay = layoutText(ch);
		g = {w: lay.width, cells: lay.pixels.map((p) => [p.x, 6 - p.y] as [number, number])};
		if (ch === ' ') g.w = 3;
	}
	cache.set(ch, g);
	return g;
};

// Ширина строки в пикселях шрифта
export const pixelWidth = (text: string) => {
	let w = 0;
	for (const ch of text) w += glyph(ch).w + 1;
	return Math.max(0, w - 1);
};

export type PixelTextOpts = {
	// размер пикселя шрифта (логические px экрана)
	px?: number;
	color?: string;
	// тень как в игре: на пиксель вниз-вправо, тёмная копия цвета
	shadow?: string | null;
	align?: 'left' | 'center' | 'right';
	alpha?: number;
};

// Нарисовать строку: (x, y) — по align и ВЕРХ заглавной буквы. Пиксели привязаны к сетке устройства.
export const drawPixelText = (ctx: CanvasRenderingContext2D, text: string, x: number, y: number, opts: PixelTextOpts = {}) => {
	const {px = 2, color = '#ffffff', shadow = '#3f3f3f', align = 'left', alpha = 1} = opts;
	if (alpha <= 0) return;
	const w = pixelWidth(text) * px;
	const x0 = align === 'center' ? x - w / 2 : align === 'right' ? x - w : x;
	const m = ctx.getTransform();
	const s = Math.hypot(m.a, m.b);
	// рисуем в пикселях устройства: целый размер пикселя шрифта
	const p = Math.max(1, Math.round(px * s));
	const ox = Math.round(m.e + x0 * s);
	const oy = Math.round(m.f + y * s);
	ctx.save();
	ctx.setTransform(1, 0, 0, 1, 0, 0);
	ctx.globalAlpha *= alpha;
	const pass = (dx: number, col: string) => {
		ctx.fillStyle = col;
		let cx = 0;
		for (const ch of text) {
			const g = glyph(ch);
			for (const [gx, gy] of g.cells) ctx.fillRect(ox + (cx + gx) * p + dx, oy + gy * p + dx, p, p);
			cx += g.w + 1;
		}
	};
	if (shadow) pass(p, shadow);
	pass(0, color);
	ctx.restore();
};

// Всё время здесь — ГЛОБАЛЬНОЕ (секунды от начала ролика).
// Сцена b-room начинается в 16.0: локальное время = глобальное − 16 (см. sceneStart в timeline.ts).

// Быстрая часть: 150 BPM, размер 4/4
export const BPM = 150;
// доля (четверть), секунды
export const BEAT = 0.4;
// такт, секунды
export const BAR = 1.6;
// шестнадцатая, секунды
export const STEP = 0.1;

// Вступление (0–8): 75 BPM — вдвое медленнее, доля 0.8 с, восьмая 0.4 с (та же сетка 0.4)
export const INTRO_BPM = 75;
export const INTRO_BEAT = 0.8;

// убрать хвосты двоичной арифметики: 9.6 + 4 * 0.4 = 11.200000000000001 -> 11.2
const r6 = (x: number) => Math.round(x * 1e6) / 1e6;

// Сильная доля 1-го такта быстрой части
export const RUSH_START = 9.6;
// Финальный аккорд (после него — только звенящий хвост до чёрного кадра)
export const RUSH_END = 29.6;
export const VIDEO_END = 30;

// Время доли n (n = 0, 1, 2 … — сколько долей прошло от RUSH_START): beatTime(4) = 11.2
export const beatTime = (n: number) => r6(RUSH_START + n * BEAT);

// Время доли beat (1..4) в такте bar (1, 2 …) — нумерация как у музыкантов: barTime(1) = 9.6, barTime(4, 3) = 15.2
export const barTime = (bar: number, beat = 1) => r6(RUSH_START + (bar - 1) * BAR + (beat - 1) * BEAT);

// Сколько долей от RUSH_START (дробное между долями)
export const beatIndex = (t: number) => r6((t - RUSH_START) / BEAT);

// Ближайшая доля (для t до 9.6 — тоже сетка 0.4: она совпадает с восьмыми вступления)
export const snapToBeat = (t: number) => beatTime(Math.round((t - RUSH_START) / BEAT));

// Лежит ли t на доле (допуск — полкадра при 60 к/с)
export const isOnBeat = (t: number, tol = 1 / 120) => Math.abs(t - snapToBeat(t)) <= tol;


// Сколько верхних строк символа выступает над обычной высотой заглавной буквы
const ASCENT: Record<string, number> = {Ё: 2};

// Кириллические буквы, совпадающие по форме с латинскими
const ALIAS: Record<string, string> = {
	А: 'A',
	В: 'B',
	Е: 'E',
	К: 'K',
	М: 'M',
	Н: 'H',
	О: 'O',
	Р: 'P',
	С: 'C',
	Т: 'T',
	Х: 'X',
	а: 'a',
	е: 'e',
	о: 'o',
	р: 'p',
	с: 'c',
	у: 'y',
	х: 'x',
};

const resolve = (ch: string): string | null => {
	if (G[ch]) return ch;
	if (ALIAS[ch]) return ALIAS[ch];
	const up = ch.toUpperCase();
	if (G[up]) return up;
	if (ALIAS[up]) return ALIAS[up];
	return null;
};

// Есть ли у шрифта такой символ (строчная кириллица рисуется заглавными)
export const hasGlyph = (ch: string) => resolve(ch) !== null;

export type TextPixel = {
	// координаты левого нижнего угла пикселя; y растёт вверх, базовая линия y = 0
	x: number;
	y: number;
	glyph: number;
	// 0 = верх буквы, 1 = низ (для градиента)
	v: number;
};

export type TextLayout = {
	pixels: TextPixel[];
	width: number;
	// центр каждого символа по x
	glyphCenters: number[];
};

// Высота заглавной буквы в пикселях шрифта
export const FONT_CAP = 7;

export const layoutText = (text: string): TextLayout => {
	const pixels: TextPixel[] = [];
	const glyphCenters: number[] = [];
	let cursor = 0;
	let glyph = 0;
	for (const ch of text) {
		const key = resolve(ch) ?? '?';
		const rows = G[key];
		const up = ASCENT[key] ?? 0;
		const w = rows[0].length;
		if (ch !== ' ') {
			for (let r = 0; r < rows.length; r++) {
				for (let c = 0; c < w; c++) {
					if (rows[r][c] === '#') {
						const row = r - up;
						pixels.push({x: cursor + c, y: 6 - row, glyph, v: Math.min(1, Math.max(0, row / 6))});
					}
				}
			}
		}
		glyphCenters.push(cursor + w / 2);
		cursor += w + 1;
		glyph++;
	}
	return {pixels, width: Math.max(0, cursor - 1), glyphCenters};
};

// Ширина строки в пикселях шрифта (умножить на px, чтобы получить размер надписи)
export const textWidth = (text: string) => layoutText(text).width;
